def get_product(product_id: str) -> dict | None:
    """Get the product data served by this provider.

    Fields delegated to the specialised providers (see delegation.py) are not served.
    """
    product = PRODUCTS.get(product_id)
    if product is None:
        return None
    delegated = DELEGATED_FIELDS.get(product_id, frozenset())
    return {key: value for key, value in product.items() if key not in delegated}


def get_all_products() -> list[dict]:
    """Get all products."""
    return list(PRODUCTS.values())


def get_products_by_type(product_type: str) -> list[dict]:
    """Get products filtered by type."""
    return [get_product(pid) for pid, p in PRODUCTS.items() if p["product_type"] == product_type]


def search_products(query: str) -> list[dict]:
    """Simple text search across product fields."""
    query = query.lower()
    results = []
    for p in PRODUCTS.values():
        searchable = f"{p['manufacturer']} {p['model']} {p['product_type']} {p['product_id']} {p.get('brand_name', '')}".lower()
        if query in searchable:
            results.append(get_product(p["product_id"]))
    return results
