# Lifecycle phases (beginning, middle and end of life) and the phase of every modelled
# lifecycle event. Custom DPP templates can be assigned to a phase instead of (or in
# addition to) one of the predefined events; a template that only carries a phase counts
# for every event of that phase in the dynamic recommendation layer.
LIFECYCLE_PHASES: dict[str, str] = {
    "beginning_of_life": "Beginning of Life",
    "middle_of_life": "Middle of Life (Use & Service)",
    "end_of_life": "End of Life",
}

EVENT_PHASES: dict[str, str] = {
    "purchase": "beginning_of_life",
    "maintenance": "middle_of_life",
    "repair": "middle_of_life",
    "resale": "middle_of_life",
    "recycling": "end_of_life",
    "disposal": "end_of_life",
}


def phase_for_event(event: str | None) -> str | None:
    """Return the lifecycle phase of a modelled event (None for unknown or missing events)."""
    return EVENT_PHASES.get(event) if event else None


def categories_for_fields(field_names: Iterable[str]) -> list[str]:
    """Return the sorted set of data categories covered by the given field names."""
    return sorted({FIELD_CATEGORIES[name] for name in field_names if name in FIELD_CATEGORIES})


def categories_for_products(products: Iterable[dict]) -> list[str]:
    """Return the data categories for which at least one product carries a non-empty value."""
    fields = set()
    for product in products:
        for key, value in product.items():
            if not key.startswith("_") and value not in (None, [], {}, ""):
                fields.add(key)
    return categories_for_fields(fields)


def fields_for_products(products: Iterable[dict]) -> list[str]:
    """Return the sorted DPP fields for which at least one product carries a non-empty value."""
    fields = set()
    for product in products:
        for key, value in product.items():
            if not key.startswith("_") and value not in (None, [], {}, ""):
                fields.add(key)
    return sorted(fields)
